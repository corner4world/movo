import { getLocale, t } from '../composables/i18n'
import { generatedSchemaPrefixes } from '../locales/legacyRecognitionValues'

export type SchemaType = 'String' | 'Integer' | 'Number' | 'Boolean' | 'Object' | 'Array' | 'ArrayObject'

function splitFieldTokens(value: string): string[] {
  return String(value || '')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .split(/[^a-zA-Z0-9]+/)
    .map((part) => part.toLowerCase())
    .filter(Boolean)
}

function commonFieldMeaning(name: string, path: string): string {
  const tokens = splitFieldTokens(`${path}_${name}`)
  const tokenSet = new Set(tokens)
  const joined = tokens.join('_')
  if (tokenSet.has('id') || joined.endsWith('_id')) return t('schema.meaning.id')
  if (tokenSet.has('name')) return t('schema.meaning.name')
  if (tokenSet.has('title')) return t('schema.meaning.title')
  if (tokenSet.has('status') || tokenSet.has('state')) return t('schema.meaning.status')
  if (tokenSet.has('type') || tokenSet.has('category')) return t('schema.meaning.type')
  if (['count', 'total', 'num', 'quantity'].some((item) => tokenSet.has(item))) return t('schema.meaning.count')
  if (['amount', 'price', 'cost', 'fee'].some((item) => tokenSet.has(item))) return t('schema.meaning.amount')
  if (['date', 'time', 'created', 'updated'].some((item) => tokenSet.has(item))) return t('schema.meaning.date')
  if (['url', 'link', 'uri'].some((item) => tokenSet.has(item))) return t('schema.meaning.url')
  if (['desc', 'description', 'summary'].some((item) => tokenSet.has(item))) return t('schema.meaning.description')
  if (tokenSet.has('content') || tokenSet.has('text')) return t('schema.meaning.content')
  if (tokenSet.has('message') || tokenSet.has('msg')) return t('schema.meaning.message')
  if (tokenSet.has('code')) return t('schema.meaning.code')
  if (['score', 'rate', 'ratio'].some((item) => tokenSet.has(item))) return t('schema.meaning.score')
  return ''
}

export function sampleArrayItem(values: unknown[]): unknown {
  const objectItems = values.filter((item) => item && typeof item === 'object' && !Array.isArray(item))
  if (!objectItems.length) return values.find((item) => item !== null && item !== undefined)
  return objectItems.slice(0, 10).reduce<Record<string, unknown>>((merged, item) => {
    Object.assign(merged, item as Record<string, unknown>)
    return merged
  }, {})
}

function childFieldSummary(value: unknown): string {
  let record: Record<string, unknown> | null = null
  if (Array.isArray(value)) {
    const sample = sampleArrayItem(value)
    if (sample && typeof sample === 'object' && !Array.isArray(sample)) record = sample as Record<string, unknown>
  } else if (value && typeof value === 'object') {
    record = value as Record<string, unknown>
  }
  if (!record) return ''
  const keys = Object.keys(record).filter(Boolean).slice(0, 6)
  if (!keys.length) return ''
  const separator = getLocale() === 'zh' ? '、' : ', '
  const more = Object.keys(record).length > keys.length ? t('schema.childMore') : ''
  return t('schema.childSummary', { keys: keys.join(separator), more })
}

export function schemaDescriptionForValue(name: string, value: unknown, type: SchemaType, path = name): string {
  const fieldPath = path || name
  const children = childFieldSummary(value)
  if (Array.isArray(value)) return t('schema.arrayDescription', { path: fieldPath, children })
  if (value && typeof value === 'object') return t('schema.objectDescription', { path: fieldPath, children })
  const meaning = commonFieldMeaning(name, fieldPath)
  return t('schema.fieldDescription', {
    path: fieldPath,
    type: t(`schema.type.${type}`),
    meaning: meaning ? t('schema.fieldMeaning', { meaning }) : '',
  })
}

export function pathObjectDescription(path: string): string {
  return t('schema.pathObjectDescription', { path })
}

export function isAutoGeneratedDescription(value: unknown): boolean {
  const text = String(value || '').trim()
  return !text || generatedSchemaPrefixes.some((prefix) => text.startsWith(prefix))
}
